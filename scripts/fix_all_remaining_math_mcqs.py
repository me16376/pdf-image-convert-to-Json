def apply_fixes():
    fixed_files = set()
    total_fixed = 0

    for (fname, qid), fix in MATH_SPECIFIC_FIXES.items():
        fpath = os.path.join(MATH_DIR, fname)
        if not os.path.exists(fpath): continue
        with open(fpath, 'r', encoding='utf-8') as f:
            d = json.load(f)

        for q in d['questions']:
            if q['id'] == qid:
                for k, v in fix.items():
                    q[k] = v
                total_fixed += 1
                fixed_files.add(fname)
                break

        with open(fpath, 'w', encoding='utf-8') as f:
            json.dump(d, f, ensure_ascii=False, indent=2)

    print(f"Successfully applied {total_fixed} targeted MCQ fixes across {len(fixed_files)} Math files!")

if __name__ == '__main__':
    apply_fixes()
